"""Export the confirmed mockups (S1 Slate) to design/screens/*.html.

The canvas versions (.dc.html) use the design canvas runtime. These static copies open in any
browser, load ../tokens.css and use var(--token) in inline styles, so the screens stay tied to the
design system. Run from the repo root:  python3 design/source/export_static.py
"""
import html
import os
import re
import sys

sys.path.insert(0, os.path.dirname(__file__))
import chrome  # noqa: E402
import screens  # noqa: E402
from sheet_svg import sheet_svg  # noqa: E402

ROOT = os.path.join(os.path.dirname(__file__), '..', 'screens')

# (file, screen function, skin, title)
PAGES = [
    ('01-home', 'FStart', 'S1', 'Home'),
    ('02-compare-waiting', 'FCompareEmpty', 'S1', 'Compare · waiting for the 2nd file'),
    ('03-compare-running', 'FCompareRunning', 'S1', 'Compare · running'),
    ('04-compare-result', 'FCompare', 'S1', 'Compare · side by side + command suggestions'),
    ('05-compare-overlay', 'FOverlay', 'S1', 'Compare · overlay'),
    ('06-export-pdf', 'FExport', 'S1', 'Export PDF dialog'),
    ('07-review-line-osnap', 'FReviewLine', 'S1', 'Review · LINE + OSNAP + layers'),
    ('08-review-hatch', 'FReviewHatch', 'S1', 'Review · HATCH'),
    ('09-focus-mode-dark-view', 'FFocus', 'S2', 'Focus mode (F11) · dark drawing view on'),
    ('10-settings', 'FSettings', 'S1', 'Settings · language, OSNAP, aliases'),
    ('11-error-empty', 'FError', 'S1', 'Error & empty states'),
    ('12-transparent-png', 'FPng', 'S1', 'Transparent PNG'),
    ('13-open-drawing', 'FOpen', 'S1', 'Open drawing dialog (app file browser)'),
]

# skin key -> token name (only colors that tokens.css defines)
TOKEN_OF = {
    'chrome': '--color-chrome', 'app': '--color-background', 'panel': '--color-surface', 'panel2': '--color-surface-sunken',
    'canvas': '--color-canvas', 'border': '--color-border', 'soft': '--color-border-subtle', 'field': '--color-border-strong',
    'text': '--color-text', 'text2': '--color-text-secondary', 'muted': '--color-text-muted', 'faint': '--color-text-faint',
    'accent': '--color-accent', 'primary': '--color-primary', 'pressed': '--color-surface-pressed', 'primaryDeep': '--color-primary-deep',
    'red': '--markup-red', 'redText': '--color-danger', 'yellow': '--markup-yellow', 'green': '--color-success', 'warn': '--color-warning',
    'snap': '--snap-marker',
}

sheets = {}


def sheet_file(attrs):
    a = dict(re.findall(r'([\w-]+)="([^"]*)"', attrs))
    key = dict(
        version=a.get('version', 'new'),
        show_marks=a.get('show-marks', '{{true}}') != '{{false}}',
        selected=int(re.sub(r'\D', '', a.get('selected', '1')) or 1),
        review=a.get('review') == '{{true}}',
        paper=a.get('paper', '#ffffff'), ink=a.get('ink', '#1b1f24'), grid=a.get('grid', '#9aa1ab'),
    )
    if key['review']:
        key['show_marks'] = False
    name = 'sheet-{version}{m}{r}{c}'.format(
        version=key['version'], m='-marks%d' % key['selected'] if key['show_marks'] and key['version'] == 'new' else '',
        r='-review' if key['review'] else '',
        c='' if key['ink'] == '#1b1f24' else '-ink' + key['ink'].lstrip('#') + ('-clear' if key['paper'] == 'transparent' else ''))
    sheets[name] = key
    return f'assets/{name}.svg'


def tokenize_styles(body):
    hex_to_var = {}
    for k, var in TOKEN_OF.items():
        v = chrome.T.get(k)
        if v and v.startswith('#'):
            hex_to_var.setdefault(v.lower(), var)

    def fix_style(m):
        st = m.group(1)
        st = re.sub(r'#[0-9a-fA-F]{6}\b', lambda h: f'var({hex_to_var[h.group(0).lower()]})' if h.group(0).lower() in hex_to_var else h.group(0), st)
        st = st.replace("'JetBrains Mono', monospace", 'var(--font-family-mono)').replace("'Pretendard', sans-serif", 'var(--font-family-base)')
        return f'style="{st}"'
    return re.sub(r'style="([^"]*)"', fix_style, body)


def to_static(dc_html, title):
    body = re.search(r'</helmet>\s*(.*)\s*</x-dc>', dc_html, re.S).group(1)
    body = re.sub(r'<dc-import name="Sheet"([^>]*)></dc-import>',
                  lambda m: f'<img src="{sheet_file(m.group(1))}" alt="Sample drawing S-101" style="display: block; width: 100%; height: 100%">', body)
    body = tokenize_styles(body)
    return f'''<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=1440">
<title>{html.escape(title)} · Sam Drawing Tools</title>
<link rel="stylesheet" href="../tokens.css">
<link rel="stylesheet" href="https://cdn.jsdelivr.net/gh/orioncactus/pretendard@v1.3.9/dist/web/static/pretendard.css">
<link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=JetBrains+Mono:wght@400;500;600&amp;display=swap">
<style>body{{margin:0;background:var(--color-chrome)}} .frame{{width:1440px;margin:0 auto}} a{{color:var(--color-accent)}}</style>
</head>
<body>
<!-- Confirmed mockup (static copy). Generated by design/source/export_static.py — edit the generator, not this file. -->
<div class="frame">
{body}
</div>
</body>
</html>
'''


def main():
    os.makedirs(os.path.join(ROOT, 'assets'), exist_ok=True)
    links = []
    for fname, fn, skin, title in PAGES:
        chrome.apply_skin(skin)
        out = to_static(screens.SCREENS[fn](), title)
        open(os.path.join(ROOT, fname + '.html'), 'w', encoding='utf-8').write(out)
        links.append(f'<li><a href="{fname}.html">{html.escape(title)}</a> <span>{fname}.html</span></li>')
        print(fname, len(out))
    for name, key in sheets.items():
        open(os.path.join(ROOT, 'assets', name + '.svg'), 'w', encoding='utf-8').write(sheet_svg(**key))
        print('assets/' + name + '.svg')
    index = f'''<!doctype html>
<html lang="en"><head><meta charset="utf-8"><title>Confirmed screens · Sam Drawing Tools</title>
<link rel="stylesheet" href="../tokens.css">
<link rel="stylesheet" href="https://cdn.jsdelivr.net/gh/orioncactus/pretendard@v1.3.9/dist/web/static/pretendard.css">
<style>body{{margin:0;padding:var(--space-8);background:var(--color-background);color:var(--color-text);font-family:var(--font-family-base)}}
h1{{font-size:var(--font-size-xl)}} li{{margin:var(--space-2) 0}} a{{color:var(--color-accent)}} span{{color:var(--color-text-faint);font-family:var(--font-family-mono);font-size:var(--font-size-xs)}}</style>
</head><body><h1>Sam Drawing Tools — confirmed screens (S1 Slate, EN)</h1><ol>{"".join(links)}</ol></body></html>
'''
    open(os.path.join(ROOT, 'index.html'), 'w', encoding='utf-8').write(index)


if __name__ == '__main__':
    main()
